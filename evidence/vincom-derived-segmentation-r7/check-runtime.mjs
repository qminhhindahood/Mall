import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import ts from 'typescript';
import {pathToFileURL} from 'node:url';
import {approvedGeometry} from '../../scripts/approved-overlay.mjs';
import {loadDerivedSegmentation,deriveSegmentedGeometry,derivedDirectory} from '../../scripts/vincom-segmentation-overlay.mjs';
import {applyPrecisionHolds} from '../../src/data/precision-holds.ts';
import {applyAssociationSupplement} from '../../src/data/association-supplement.ts';
const read=p=>JSON.parse(readFileSync(p));
const packet=loadDerivedSegmentation(process.cwd());
assert.equal(packet.activation,'accepted-independent-residual-review');
const raw=read('data/malls/vincom-dong-khoi/floor-geometry.json');
const before=JSON.stringify(raw);
const geometry=approvedGeometry(process.cwd(),'vincom-dong-khoi',raw);
assert.equal(JSON.stringify(raw),before);
assert.deepEqual(geometry,read('evidence/vincom-derived-segmentation-r7/staged-geometry.json'));
assert.throws(()=>deriveSegmentedGeometry(geometry,packet),/revision drift/);
const overlay=read('data/malls/vincom-dong-khoi/approved-regions.json');
const base={...raw,revision:packet.approvedGeometryRevision,floors:raw.floors.map(f=>({...f,regions:[...f.regions,...(overlay.floors.find(x=>x.floorId===f.id)?.regions??[])]}))};
const changed=structuredClone(base);changed.floors.find(f=>f.id==='B3').regions.find(r=>r.id===packet.parents[0].original.id).outer[0][0]+=0.001;
assert.throws(()=>deriveSegmentedGeometry(changed,packet),/parent payload drift/);
const collision=structuredClone(packet);collision.children[0].region.id=collision.parents[0].original.id;
assert.throws(()=>deriveSegmentedGeometry(base,collision),/collision/);
const lostResidual=structuredClone(packet);lostResidual.parents[0].residual=[];
assert.throws(()=>deriveSegmentedGeometry(base,lostResidual),/residual must remain/);
const held=applyPrecisionHolds(read('data/malls/vincom-dong-khoi/directory.json'),read('data/research/vincom-precision-holds-2026-10-21-r1.json'));
const supplement=read('data/research/vincom-source-associations-2026-10-21-r1.json');
const associated=applyAssociationSupplement(held,geometry,supplement,read(supplement.reviewEvidence.path));
const content=derivedDirectory(process.cwd(),associated,geometry);
let code=ts.transpileModule(readFileSync('src/data/content.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
let enrichment=readFileSync('src/data/enrichment.ts','utf8').replaceAll('import.meta.env.PUBLIC_CONTENT_FIXTURES',"'0'").replaceAll('import.meta.env.PUBLIC_DISCOVERY_REVIEW',"'0'");
for(const name of ['enrichment-accepted','enrichment-proposals'])enrichment=enrichment.replace("(await import('./"+name+".json')).default",JSON.stringify(read('src/data/'+name+'.json')));
const enrichmentCode=ts.transpileModule(enrichment,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
code=code.replace("'./enrichment'",JSON.stringify('data:text/javascript;base64,'+Buffer.from(enrichmentCode).toString('base64')));
const {validateContent}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
validateContent(content,'vincom-dong-khoi',geometry);
assert.equal(content.destinations.filter(d=>d.locations.some(l=>l.areaIds.length)).length,35);
for(const id of packet.protectedDestinationIds)assert.ok(content.destinations.find(d=>d.id===id).locations.every(l=>!l.areaIds.length));
for(const child of packet.children)assert.deepEqual(content.destinations.find(d=>d.id===child.destinationId).locations.find(l=>l.floorId==='B3').areaIds,[child.areaId]);
writeFileSync('evidence/vincom-derived-segmentation-r7/activation-check.json',JSON.stringify({result:'pass',vincomLinkedListings:35,combinedLinkedListings:191,combinedFloorAssociations:192,protectedHolds:5,exactChildren:4,geometryEqualsReviewedStaging:true,contentValidation:'pass'},null,2)+'\n');
console.log('PASS: active geometry equals reviewed staging; four associations and five holds; directory validation; immutable base; drift/collision/residual guards.');
